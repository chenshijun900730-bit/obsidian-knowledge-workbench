const dictionaries: Record<WorkbenchLocale, Record<DirectoryPickerMessageKey, string>> = {
  "zh-CN": zhCN,
  en,
};

export interface DirectoryPickerI18n {
  readonly locale: WorkbenchLocale;
  t(key: DirectoryPickerMessageKey, values?: Readonly<Record<string, string | number>>): string;
}

export const createDirectoryPickerI18n = (locale: WorkbenchLocale): DirectoryPickerI18n => ({
  locale,
  t(key, values = {}) {
    return dictionaries[locale][key].replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/gu, (_, name: string) => {
      const value = values[name];
      if (value === undefined) throw new Error(`i18n-interpolation-missing:${name}`);
      return String(value);
    });
  },
});
